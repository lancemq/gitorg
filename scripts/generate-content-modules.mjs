import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const contentTsPath = path.join(root, "lib", "content.ts");
const outputPath = path.join(root, "lib", "content-modules.ts");

function extractQuotedStrings(block) {
  return Array.from(block.matchAll(/"([^"]+)"/g), (match) => match[1]);
}

function extractArrayBlock(source, startMarker, endMarker) {
  const start = source.indexOf(startMarker);
  if (start === -1) {
    throw new Error(`Unable to find start marker: ${startMarker}`);
  }

  const end = source.indexOf(endMarker, start);
  if (end === -1) {
    throw new Error(`Unable to find end marker: ${endMarker}`);
  }

  return source.slice(start + startMarker.length, end);
}

function generateImports(registry, locale) {
  return registry
    .map((docPath) => {
      const key = docPath.includes("-") || docPath.includes("/") ? `"${docPath}"` : docPath;
      return `    ${key}: () => import("@/content/${locale}/${docPath}.mdx"),`;
    })
    .join("\n");
}

async function main() {
  const contentSource = await fs.readFile(contentTsPath, "utf8");
  const docPathRegistry = extractQuotedStrings(
    extractArrayBlock(contentSource, "export const docPathRegistry = [", "] as const;"),
  );

  // EN offline docs stay in the registry (ZH counterparts remain online) but
  // their MDX files are archived away, so EN must not emit imports for them.
  const enOffline = new Set(
    extractQuotedStrings(
      extractArrayBlock(
        contentSource,
        "export const enOfflineDocPaths: ReadonlySet<string> = new Set([",
        "]);",
      ),
    ),
  );
  const enRegistry = docPathRegistry.filter((docPath) => !enOffline.has(docPath));

  const lines = [
    `// Auto-generated by scripts/generate-content-modules.mjs`,
    `// Do not edit manually. Run \`node scripts/generate-content-modules.mjs\` to regenerate.`,
    `//`,
    `// The EN map intentionally omits enOfflineDocPaths entries (archived MDX),`,
    `// so lookup is typed loosely: use getDocModule() below for safe access.`,
    ``,
    `import type { DocPath } from "./content";`,
    `import type { Locale } from "./i18n";`,
    ``,
    `type ContentLoader = () => Promise<unknown>;`,
    ``,
    `export const contentModules = {`,
    `  zh: {`,
    generateImports(docPathRegistry, "zh"),
    `  },`,
    `  en: {`,
    generateImports(enRegistry, "en"),
    `  },`,
    `} as const;`,
    ``,
    `export function getDocModule(locale: Locale, docPath: DocPath): ContentLoader | undefined {`,
    `  const map: Record<string, ContentLoader | undefined> = contentModules[locale];`,
    `  return map[docPath];`,
    `}`,
    ``,
  ];

  await fs.writeFile(outputPath, lines.join("\n") + "\n", "utf8");
  console.log(`Generated ${outputPath} with ${docPathRegistry.length} docs per locale.`);
}

await main();
